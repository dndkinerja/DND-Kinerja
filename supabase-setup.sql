-- DND Kinerja shared backend for Supabase + GitHub Pages
-- Run this file in Supabase Dashboard > SQL Editor after creating the project.
create table if not exists public.dnd_members (
  id bigint generated by default as identity primary key,
  auth_uid uuid unique references auth.users(id) on delete set null,
  username text not null unique,
  email text unique,
  full_name text not null,
  title text default '',
  role text not null default 'user' check (role in ('admin','user')),
  approved boolean not null default false,
  avatar text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.dnd_shared_state (
  singleton boolean primary key default true check (singleton),
  settings jsonb not null default '{}'::jsonb,
  tasks jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);
insert into public.dnd_shared_state(singleton) values(true) on conflict(singleton) do nothing;

create or replace function public.dnd_is_admin()
returns boolean language sql stable security definer set search_path=public,auth as $$
  select exists(select 1 from public.dnd_members m where m.auth_uid=auth.uid() and m.approved and m.role='admin')
$$;
create or replace function public.dnd_is_approved()
returns boolean language sql stable security definer set search_path=public,auth as $$
  select exists(select 1 from public.dnd_members m where m.auth_uid=auth.uid() and m.approved)
$$;

create or replace function public.dnd_link_auth_user()
returns trigger language plpgsql security definer set search_path=public,auth as $$
declare meta jsonb := coalesce(new.raw_user_meta_data,'{}'::jsonb); existing_id bigint;
begin
  if coalesce(meta->>'username','')='' or coalesce(meta->>'full_name','')='' then
    raise exception 'username and full_name are required';
  end if;
  select id into existing_id from public.dnd_members where lower(email)=lower(new.email) or lower(username)=lower(meta->>'username') limit 1;
  if existing_id is not null then
    update public.dnd_members set auth_uid=new.id,email=new.email,username=meta->>'username',full_name=meta->>'full_name',title=coalesce(meta->>'title',title) where id=existing_id and auth_uid is null;
  else
    insert into public.dnd_members(auth_uid,username,email,full_name,title,role,approved)
    values(new.id,meta->>'username',new.email,meta->>'full_name',coalesce(meta->>'title',''),'user',false);
  end if;
  return new;
end $$;
drop trigger if exists dnd_auth_user_created on auth.users;
create trigger dnd_auth_user_created after insert on auth.users for each row execute procedure public.dnd_link_auth_user();

create or replace function public.dnd_protect_member_fields()
returns trigger language plpgsql security definer set search_path=public,auth as $$
begin
  if not public.dnd_is_admin() then
    if old.auth_uid is distinct from new.auth_uid or old.role is distinct from new.role or old.approved is distinct from new.approved or old.email is distinct from new.email or old.username is distinct from new.username or old.id is distinct from new.id then
      raise exception 'Only an administrator can change account access fields';
    end if;
    if old.auth_uid is distinct from auth.uid() then raise exception 'Cannot edit another account'; end if;
  end if;
  return new;
end $$;
drop trigger if exists dnd_member_fields_guard on public.dnd_members;
create trigger dnd_member_fields_guard before update on public.dnd_members for each row execute procedure public.dnd_protect_member_fields();

alter table public.dnd_members enable row level security;
revoke all on public.dnd_members from anon;
grant select, update, insert, delete on public.dnd_members to authenticated;
drop policy if exists dnd_members_read on public.dnd_members;
create policy dnd_members_read on public.dnd_members for select to authenticated using (auth_uid=auth.uid() or (approved and public.dnd_is_approved()) or public.dnd_is_admin());
drop policy if exists dnd_members_self_update on public.dnd_members;
create policy dnd_members_self_update on public.dnd_members for update to authenticated using (auth_uid=auth.uid() or public.dnd_is_admin()) with check (auth_uid=auth.uid() or public.dnd_is_admin());
drop policy if exists dnd_members_admin_insert on public.dnd_members;
create policy dnd_members_admin_insert on public.dnd_members for insert to authenticated with check (public.dnd_is_admin());
drop policy if exists dnd_members_admin_delete on public.dnd_members;
create policy dnd_members_admin_delete on public.dnd_members for delete to authenticated using (public.dnd_is_admin());

alter table public.dnd_shared_state enable row level security;
revoke all on public.dnd_shared_state from anon,authenticated;
grant select, update on public.dnd_shared_state to authenticated;
drop policy if exists dnd_state_read on public.dnd_shared_state;
create policy dnd_state_read on public.dnd_shared_state for select to authenticated using (public.dnd_is_approved());
drop policy if exists dnd_state_admin_write on public.dnd_shared_state;
create policy dnd_state_admin_write on public.dnd_shared_state for update to authenticated using (public.dnd_is_admin()) with check (public.dnd_is_admin());

create or replace function public.dnd_get_state()
returns jsonb language plpgsql stable security definer set search_path=public,auth as $$
declare result jsonb;
begin
  if not public.dnd_is_approved() then raise exception 'Account is awaiting administrator approval'; end if;
  select jsonb_build_object('settings',settings,'tasks',tasks) into result from public.dnd_shared_state where singleton=true;
  return result;
end $$;
grant execute on function public.dnd_get_state() to authenticated;

create or replace function public.dnd_sync_state(p_settings jsonb,p_tasks jsonb)
returns void language plpgsql security definer set search_path=public,auth as $$
declare m public.dnd_members%rowtype; oldrow public.dnd_shared_state%rowtype; oldtask jsonb; newtask jsonb;
begin
  select * into m from public.dnd_members where auth_uid=auth.uid() and approved;
  if m.id is null then raise exception 'Account is awaiting administrator approval'; end if;
  select * into oldrow from public.dnd_shared_state where singleton=true for update;
  if m.role='admin' then
    update public.dnd_shared_state set settings=coalesce(p_settings,'{}'::jsonb),tasks=coalesce(p_tasks,'[]'::jsonb),updated_at=now() where singleton=true;
  else
    if p_settings is distinct from oldrow.settings then raise exception 'Only an administrator can change organization settings'; end if;
    if jsonb_typeof(p_tasks)<>'array' then raise exception 'Tasks must be an array'; end if;
    for oldtask in select value from jsonb_array_elements(oldrow.tasks) loop
      select value into newtask from jsonb_array_elements(p_tasks) where value->>'id'=oldtask->>'id' limit 1;
      if newtask is null then
        if (oldtask->>'pic')::bigint<>m.id then raise exception 'Cannot delete another employee task'; end if;
      elsif newtask is distinct from oldtask then
        if (oldtask->>'pic')::bigint<>m.id or (newtask->>'pic')::bigint<>m.id then raise exception 'Can only edit tasks assigned to your account'; end if;
      end if;
      newtask:=null;
    end loop;
    for newtask in select value from jsonb_array_elements(p_tasks) loop
      if not exists(select 1 from jsonb_array_elements(oldrow.tasks) x where x->>'id'=newtask->>'id') and (newtask->>'pic')::bigint<>m.id then
        raise exception 'New tasks must be assigned to your account';
      end if;
    end loop;
    update public.dnd_shared_state set tasks=p_tasks,updated_at=now() where singleton=true;
  end if;
end $$;
grant execute on function public.dnd_sync_state(jsonb,jsonb) to authenticated;
create or replace function public.dnd_admin_sync_members(p_users jsonb)
returns void language plpgsql security definer set search_path=public,auth as $$
declare m jsonb; actor_id bigint;
begin
  if not public.dnd_is_admin() then raise exception 'Administrator access required'; end if;
  select id into actor_id from public.dnd_members where auth_uid=auth.uid();
  for m in select value from jsonb_array_elements(coalesce(p_users,'[]'::jsonb)) loop
    insert into public.dnd_members(id,username,email,full_name,title,role,approved,avatar)
    values((m->>'id')::bigint,m->>'username',nullif(m->>'email',''),coalesce(m->>'full_name','Pegawai'),coalesce(m->>'title',''),case when m->>'role'='admin' then 'admin' else 'user' end,coalesce((m->>'approved')::boolean,false),coalesce(m->>'avatar',''))
    on conflict(id) do update set username=excluded.username,email=excluded.email,full_name=excluded.full_name,title=excluded.title,role=excluded.role,approved=excluded.approved,avatar=excluded.avatar;
  end loop;
  perform setval(pg_get_serial_sequence('public.dnd_members','id'),coalesce((select max(id) from public.dnd_members),1),true);
  delete from public.dnd_members where id<>actor_id and not exists(select 1 from jsonb_array_elements(coalesce(p_users,'[]'::jsonb)) x where (x->>'id')::bigint=dnd_members.id);
end $$;
grant execute on function public.dnd_admin_sync_members(jsonb) to authenticated;